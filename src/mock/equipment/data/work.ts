/**
 * 工单域种子（附录 B3：工单 12 张、各状态都有）。
 *
 * 两点为演示而编排，不是随手填的：
 * 1. **8 张 `source=报警转单` 与 `data/monitor.ts` 里 8 条已转工单的报警号一一对应**，
 *    客户从报警中心点「查看工单」必须能落到真实存在的那张单上（双向可追是 B2 状态机的卖点）。
 * 2. 状态分布覆盖 B2 全流程：待派工 1 / 已派工 1 / 执行中 2 / 待验证 2 / 已关闭 6，
 *    工单管理的状态色标和「按钮按状态置灰」才有样本可看。
 *
 * `steps[]` 是工单详情页时间轴的唯一数据源（L5 版式），每步都带 `by`——
 * 派工到人、验证到主管，是设备管理系统的责任链，缺一个就不可信。
 */

function step(status: WoStep["status"], at: string, by: string, note: string): WoStep {
  return { status, at, by, note };
}

function wo(
  id: string,
  title: string,
  eqId: string,
  source: WorkOrder["source"],
  priority: WorkOrder["priority"],
  status: WorkOrder["status"],
  assignee: string,
  faultDesc: string,
  planHours: number,
  actualHours: number,
  createdAt: string,
  steps: WoStep[],
  materials: WorkOrder["materials"] = [],
  photos: string[] = [],
  closedAt?: string,
): WorkOrder {
  return {
    id,
    title,
    eqId,
    source,
    faultDesc,
    priority,
    status,
    assignee,
    planHours,
    actualHours,
    materials,
    photos,
    steps,
    createdAt,
    closedAt,
  };
}

