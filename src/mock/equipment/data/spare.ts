/**
 * 寿命记录（AS0003/0004/0005 的数据核心，一条 = 一个实物）。
 *
 * 状态分布是**编排过的**（附录 B4 第 8 幕要现场展示「3 条黄、2 条红」）：
 *   正常 8 · 临期 3 · 超期 2 · 已更换 1 · 已折算 1。
 * 两个金额也要能对上剧本话术：
 *   张伟 LR-000102 超期 32h × 奖系数 20 = **+640**；
 *   赵刚 LR-000108 更换时只用 1050h、达标线 1200×90%=1080，差 30h × 罚系数 40 = **−1200**；
 *   赵刚 LR-000107 芯棒剩余 42% × 18 万 = **折算 7.56 万**（离职交接那一幕）。
 * `usedHours` 由工单工时/MES mock 累计（见 store.tickRunHours / closeWorkOrder），**不在此表写死结论字段**：
 * 奖惩金额一律结算时现算，不落库，避免改系数后历史单据口径错乱。
 */
function life(
  id: string,
  serial: string,
  spId: string,
  holder: string,
  mountedEqId: string,
  mountedAt: string,
  usedHours: number,
  lifeLimitHours: number,
  status: LifeRecord["status"],
  replacedAt?: string,
): LifeRecord {
  return { id, serial, spId, holder, mountedEqId, mountedAt, usedHours, lifeLimitHours, status, replacedAt };
}

