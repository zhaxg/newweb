/**
 * 库存流水（AS0002）。`balance` 是**动账后余额**、逐条自证账实相符——
 * 客户问「你们库存怎么对得上」时，这一列就是答案，所以它是数据而不是页面现算。
 *
 * 种子里的 balance 与 `seedSpareParts.qty` 只保证**同一备件最后一条流水**对得上当前库存；
 * 中间历史条目的 balance 是该时点的真实值（往回递减），不与现库存冲突。
 */
